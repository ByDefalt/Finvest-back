package defalt.exception

import org.springframework.http.HttpStatus

fun ErrorHttp.toHttpStatus(): HttpStatus = when (this) {
    ErrorHttp.BAD_REQUEST -> HttpStatus.BAD_REQUEST
    ErrorHttp.UNAUTHORIZED -> HttpStatus.UNAUTHORIZED
    ErrorHttp.PAYMENT_REQUIRED -> HttpStatus.PAYMENT_REQUIRED
    ErrorHttp.FORBIDDEN -> HttpStatus.FORBIDDEN
    ErrorHttp.NOT_FOUND -> HttpStatus.NOT_FOUND
    ErrorHttp.METHOD_NOT_ALLOWED -> HttpStatus.METHOD_NOT_ALLOWED
    ErrorHttp.NOT_ACCEPTABLE -> HttpStatus.NOT_ACCEPTABLE
    ErrorHttp.PROXY_AUTHENTICATION_REQUIRED -> HttpStatus.PROXY_AUTHENTICATION_REQUIRED
    ErrorHttp.REQUEST_TIMEOUT -> HttpStatus.REQUEST_TIMEOUT
    ErrorHttp.CONFLICT -> HttpStatus.CONFLICT
    ErrorHttp.GONE -> HttpStatus.GONE
    ErrorHttp.LENGTH_REQUIRED -> HttpStatus.LENGTH_REQUIRED
    ErrorHttp.PRECONDITION_FAILED -> HttpStatus.PRECONDITION_FAILED
    ErrorHttp.CONTENT_TOO_LARGE -> HttpStatus.CONTENT_TOO_LARGE
    ErrorHttp.URI_TOO_LONG -> HttpStatus.URI_TOO_LONG
    ErrorHttp.UNSUPPORTED_MEDIA_TYPE -> HttpStatus.UNSUPPORTED_MEDIA_TYPE
    ErrorHttp.REQUESTED_RANGE_NOT_SATISFIABLE -> HttpStatus.REQUESTED_RANGE_NOT_SATISFIABLE
    ErrorHttp.EXPECTATION_FAILED -> HttpStatus.EXPECTATION_FAILED
    ErrorHttp.MISDIRECTED_REQUEST -> HttpStatus.MISDIRECTED_REQUEST
    ErrorHttp.UNPROCESSABLE_CONTENT -> HttpStatus.UNPROCESSABLE_CONTENT
    ErrorHttp.LOCKED -> HttpStatus.LOCKED
    ErrorHttp.FAILED_DEPENDENCY -> HttpStatus.FAILED_DEPENDENCY
    ErrorHttp.TOO_EARLY -> HttpStatus.TOO_EARLY
    ErrorHttp.UPGRADE_REQUIRED -> HttpStatus.UPGRADE_REQUIRED
    ErrorHttp.PRECONDITION_REQUIRED -> HttpStatus.PRECONDITION_REQUIRED
    ErrorHttp.TOO_MANY_REQUESTS -> HttpStatus.TOO_MANY_REQUESTS
    ErrorHttp.REQUEST_HEADER_FIELDS_TOO_LARGE -> HttpStatus.REQUEST_HEADER_FIELDS_TOO_LARGE
    ErrorHttp.UNAVAILABLE_FOR_LEGAL_REASONS -> HttpStatus.UNAVAILABLE_FOR_LEGAL_REASONS

    ErrorHttp.INTERNAL_SERVER_ERROR -> HttpStatus.INTERNAL_SERVER_ERROR
    ErrorHttp.NOT_IMPLEMENTED -> HttpStatus.NOT_IMPLEMENTED
    ErrorHttp.BAD_GATEWAY -> HttpStatus.BAD_GATEWAY
    ErrorHttp.SERVICE_UNAVAILABLE -> HttpStatus.SERVICE_UNAVAILABLE
    ErrorHttp.GATEWAY_TIMEOUT -> HttpStatus.GATEWAY_TIMEOUT
    ErrorHttp.HTTP_VERSION_NOT_SUPPORTED -> HttpStatus.HTTP_VERSION_NOT_SUPPORTED
    ErrorHttp.VARIANT_ALSO_NEGOTIATES -> HttpStatus.VARIANT_ALSO_NEGOTIATES
    ErrorHttp.INSUFFICIENT_STORAGE -> HttpStatus.INSUFFICIENT_STORAGE
    ErrorHttp.LOOP_DETECTED -> HttpStatus.LOOP_DETECTED
    ErrorHttp.NETWORK_AUTHENTICATION_REQUIRED -> HttpStatus.NETWORK_AUTHENTICATION_REQUIRED
}