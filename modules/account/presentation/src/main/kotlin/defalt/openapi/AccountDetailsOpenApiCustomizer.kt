package defalt.openapi

import defalt.mapper.AccountDetailsMapperSolver
import defalt.models.dto.AccountDetailsDto
import defalt.models.request.AccountWithDetailsRequest
import defalt.models.response.AccountWithDetailsResponse
import io.swagger.v3.core.converter.ModelConverters
import io.swagger.v3.oas.models.OpenAPI
import io.swagger.v3.oas.models.SpecVersion
import io.swagger.v3.oas.models.media.Schema
import org.springdoc.core.customizers.GlobalOpenApiCustomizer
import org.springframework.stereotype.Component

/**
 * Documents the polymorphic `details` of the accounts in the OpenAPI document.
 *
 * springdoc only sees the [AccountDetailsDto] interface: the concrete DTOs are registered at runtime in
 * Jackson by `AccountDetailsJacksonModule`. This customizer adds the schema of the DTO of every mapper and
 * turns the `details` property of the account request and response into a `oneOf` of these schemas.
 * Like the Jackson module, it is built from the mappers: a new account type is documented without any change here.
 *
 * OpenAPI cannot express that `accountTypeCode`, a sibling of `details`, selects the schema: the mapping
 * is given in the description of `details`.
 *
 * @param mappers every details mapper, whose DTO is documented under its account type code.
 */
@Component
class AccountDetailsOpenApiCustomizer(
    private val mappers: List<AccountDetailsMapperSolver<*, *>>,
) : GlobalOpenApiCustomizer {
    /**
     * Adds the details schemas and replaces the `details` property of the account request and response.
     *
     * @param openApi OpenAPI document generated by springdoc, modified in place.
     */
    override fun customise(openApi: OpenAPI) {
        val components = openApi.components ?: return
        val converters = ModelConverters.getInstance(openApi.specVersion == SpecVersion.V31)
        val schemaNames =
            mappers
                .sortedBy { it.accountTypeCode.value }
                .associate { mapper ->
                    converters.readAll(mapper.dtoType).forEach { (name, schema) -> components.addSchemas(name, schema) }
                    mapper.accountTypeCode.value to mapper.dtoType.simpleName
                }

        listOf(AccountWithDetailsRequest::class.java, AccountWithDetailsResponse::class.java)
            .mapNotNull { components.schemas?.get(it.simpleName) }
            .forEach { schema -> schema.properties?.put(DETAILS_PROPERTY, detailsSchema(schemaNames)) }

        // Replaced by the oneOf: the interface alone describes nothing but the account id
        components.schemas?.remove(AccountDetailsDto::class.java.simpleName)
    }

    /**
     * Schema of the `details` property: one of the schemas of the details DTOs.
     *
     * @param schemaNames name of the schema of the DTO of each account type code.
     * @return the `oneOf` schema, described with the account type code of each DTO.
     */
    private fun detailsSchema(schemaNames: Map<String, String>): Schema<Any> =
        Schema<Any>().apply {
            oneOf = schemaNames.values.map { Schema<Any>().`$ref`("$SCHEMAS_REF$it") }
            description = "Details of the account, whose schema is selected by `accountTypeCode`: " +
                schemaNames.entries.joinToString { (type, schema) -> "`$type`: `$schema`" } + "."
        }

    private companion object {
        /** Name of the polymorphic property in the account request and response. */
        const val DETAILS_PROPERTY = "details"

        /** Prefix of the references to the schemas of the components. */
        const val SCHEMAS_REF = "#/components/schemas/"
    }
}
